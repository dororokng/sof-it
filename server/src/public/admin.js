// Подтверждение удаления через data-атрибут, а не через инлайн onsubmit="confirm('...')".
// Причина: EJS <%= %> экранирует значение под HTML-атрибут (' -> &#39;), но браузер
// сначала HTML-декодирует атрибут и только потом выполняет его как JS — экранированная
// кавычка доходит до JS-парсера как настоящая и разрывает строковый литерал. Если строка
// пришла от анонимного пользователя (имя из формы заявки на /admin/leads), это давало
// исполнение произвольного JS в сессии администратора. data-атрибут остаётся просто
// текстом, никакого JS из него не парсится.
document.addEventListener("submit", (e) => {
  const message = e.target.dataset && e.target.dataset.confirm;
  if (message && !window.confirm(message)) {
    e.preventDefault();
  }
});
