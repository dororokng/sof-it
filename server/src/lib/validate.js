// Формат id, задаваемого вручную в формах создания товара/новости/категории
// (см. pattern="[a-z0-9-]+" в соответствующих *.ejs). До этого раунда
// («Технический анализ по всем файлам», 2026-09-05) проверка была только в
// HTML-атрибуте pattern — обходится прямым POST-запросом или редактированием
// DOM. id используется как первичный ключ и как есть попадает в query-строку
// ссылок на сайте (?id=...) и в href-атрибуты карточек (js/render.js) без
// экранирования — без этой проверки admin-контролируемый id с символами
// вроде `"` или `<` мог бы сломать вёрстку или инжектировать разметку в
// публичные страницы каталога/новостей.
const ID_RE = /^[a-z0-9-]+$/;

export function isValidId(id) {
  return typeof id === "string" && ID_RE.test(id);
}
