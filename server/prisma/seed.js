async function main() {
  for (const c of categories) {
    await prisma.category.upsert({ where: { id: c.id }, create: c, update: c });
  }
  for (const p of products) {
    await prisma.product.upsert({ where: { id: p.id }, create: p, update: p });
  }
  for (const s of services) {
    const data = { ...s, slug: s.id };
    await prisma.service.upsert({ where: { id: s.id }, create: data, update: data });
  }
  for (const n of news) {
    await prisma.newsPost.upsert({ where: { id: n.id }, create: n, update: n });
  }
  console.log(`Загружено: ${products.length} товаров, ${services.length} услуг, ${news.length} новостей.`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
