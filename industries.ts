/**
 * Конфиги секции «Партия до и после» + «Журнал смены»: эталон (пищевое производство) +
 * 9 отраслей сайта (industries[] в js/solutions-data.js) + 14 направлений категорий
 * (industryCategories[].items[] там же — все, у кого на момент написания заведены items:
 * товары массового потребления, стройматериалы, лёгкая промышленность, мебель/дерево;
 * у «Полиграфии и упаковки» items пока пустой — карточку заводить не из чего).
 *
 * Как считается итог в колонке «Результат» (stepsMode):
 * - product — нормы этапов перемножаются: 98 % × 97 % × … = metric.resultValue;
 * - sum     — значения этапов складываются: 18 400 + 9 600 + … = metric.resultValue;
 * - control — у этапов контрольные значения без арифметики, итог задан в metric.resultValue.
 *
 * Что откуда:
 * - log[].thesis — дословно пункты «Когда нужна 1С», в исходном порядке.
 * - titles.problem — дословно один из этих пунктов.
 * - У эталона и у всех 14 направлений категорий titles.problem/solution/result взяты
 *   дословно из industryCategories[].items[].problem/solution/result (у этих записей такие
 *   поля есть в solutions-data.js) — у 9 плоских industries[] таких полей нет, там
 *   titles.solution/result — НОВЫЕ формулировки на основе блока «Специфика».
 * - metric/steps/log[].time,place,quote — иллюстративный пример, но ориентированы на
 *   реальные отраслевые нормативы (выход кирпича/пиломатериала, межлекальные потери ткани,
 *   использование кожи, точность дозирования премиксов и т.п. — см. источники в
 *   HANDOVER/чате, не хранятся в коде).
 * - Все цифры иллюстративные: в шапке карточки обязательна подпись «пример расчёта».
 */

export type StepsMode = "product" | "sum" | "control";

export interface Step {
  name: string;
  value: string; // как показывать в техкарте
  num?: number; // для product/sum: число, из которого считается итог
}

export interface Metric {
  label: string;
  unit: string;
  decimals: number;
  signed?: boolean; // показывать знак +/−; разброс может уходить в минус
  problemRange: [number, number];
  resultValue: number;
}

export interface LogEntry {
  time: string;
  place: string;
  quote: string;
  thesis: string;
}

export interface Industry {
  slug: string;
  name: string;
  caseHeader: string;
  titles: { problem: string; solution: string; result: string };
  metric: Metric;
  stepsMode: StepsMode;
  steps: Step[];
  resultLines: [string, string];
  verdictObject: string; // «Пора вести {verdictObject} в 1С»
  checkTitle: string;
  log: LogEntry[]; // 4 или 5 записей
}

